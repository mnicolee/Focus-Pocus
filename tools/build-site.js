// Build the public website into _site/.
//
//   node tools/build-site.js            # then open _site/index.html, or:
//   npx serve _site                     # (any static server works)
//
// Copies the hand-built pages in site/ and bundles logs-sample/*.json into
// assets/sample-data.js. Real logs are never read: the site only ever ships
// the sample dataset. GitHub Actions runs this on every push to main.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'site');
const SAMPLE = path.join(ROOT, 'logs-sample');
const OUT = path.join(ROOT, process.argv[2] || '_site');

fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(SRC, OUT, { recursive: true });

const sessions = [];
for (const f of fs.readdirSync(SAMPLE).sort()) {
  if (!/^\d{4}-\d{2}-\d{2}\.json$/.test(f)) continue;
  sessions.push(...JSON.parse(fs.readFileSync(path.join(SAMPLE, f), 'utf8')));
}
fs.writeFileSync(
  path.join(OUT, 'assets', 'sample-data.js'),
  '// Generated by tools/build-site.js from logs-sample/. Made-up data.\n' +
  'window.FP_SAMPLE = ' + JSON.stringify(sessions) + ';\n'
);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

console.log(`Built ${path.relative(ROOT, OUT)}/ with ${sessions.length} sample sessions`);
